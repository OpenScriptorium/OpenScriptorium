# Generates db/data/tvtms_openscriptorium_overlay.tsv from Luther's TEI
# structure. The overlay supplies German→KJV verse mappings for the
# books where Luther 1912's German tradition diverges from BOTH KJV and
# the upstream TVTMS coverage:
#
#   * Psalms — 63 chapters with title-as-v1 numbering. Upstream covers
#     only Pss 54, 64, 127. We emit explicit per-verse rows for the
#     remaining 60 chapters and for the 4 with double-line titles.
#
#   * 3 John 1:15 — Luther splits KJV's closing greeting into v14 + v15.
#
#   * Revelation 12:18 — Luther's verse division places "And I stood
#     upon the sand of the sea" at the end of ch12; KJV puts it at the
#     start of ch13:1. (Modern critical editions agree with Luther.)
#
# Re-run this script whenever the upstream TVTMS gains German rows for
# any of these passages — the generator only emits a row if upstream
# doesn't already cover it. The output is committed to the repo so the
# importer doesn't need to regenerate it on every install.
#
# Usage:
#   bin/rails runner script/generate_tvtms_overlay.rb

require "nokogiri"

OVERLAY_PATH = Rails.root.join("db/data/tvtms_openscriptorium_overlay.tsv")
LUTHER_TEI   = Rails.root.join("tmp/luther/luther-bibel.xml")
TVTMS_PATH   = Rails.root.join("tmp/tvtms/TVTMS.txt")

unless File.exist?(LUTHER_TEI)
  abort "missing #{LUTHER_TEI} — run `bin/rake import:luther1912 DOWNLOAD=true` first"
end
unless File.exist?(TVTMS_PATH)
  abort "missing #{TVTMS_PATH} — run `bin/rake import:tvtms DOWNLOAD=true` first"
end

# 1) Read Luther's psalm structure: { chapter => max_verse }
doc = Nokogiri::XML(File.read(LUTHER_TEI))
doc.remove_namespaces!
psalms_div = doc.xpath("//div[@type='book']").find { |b| b["id"] == "Lb_Ps" }
luther_psalms = Hash.new { |h, k| h[k] = [] }
psalms_div.xpath(".//ab").each do |ab|
  m = ab["id"].to_s.match(/\.(\d+)\.(\d+)\z/) or next
  luther_psalms[m[1].to_i] << m[2].to_i
end
luther_psalm_max = luther_psalms.transform_values(&:max)

# 2) Read KJV Psalms structure for diff comparison
kjv_psalms = CanonicalWork.find_by!(slug: "psalms")
kjv_psalm_max = {}
kjv_psalms.canonical_refs
          .where("array_length(hierarchy, 1) = 2")
          .pluck(:hierarchy)
          .each { |h| kjv_psalm_max[h[0]] = [kjv_psalm_max[h[0]] || 0, h[1]].max }

# 3) Find chapters already covered by upstream TVTMS German rows
upstream_german_chapters = Set.new
File.foreach(TVTMS_PATH) do |line|
  next unless line.start_with?("German\t")
  fields = line.chomp.split("\t", -1)
  src = fields[1].to_s.strip
  next unless src =~ /\APsa\.(\d+):/
  upstream_german_chapters << $1.to_i
end
puts "upstream German rows cover psalm chapters: #{upstream_german_chapters.to_a.sort.inspect}"

# 4) Build the overlay rows
rows = []

def emit(rows, source_type, src_ref, std_ref, action, note = "")
  rows << [source_type, src_ref, std_ref, action, "", "", note, "", "openscriptorium_overlay"]
end

# Header (commented for human readability — TVTMS-style $-prefix is data)
rows << ["# Open Scriptorium TVTMS overlay — German Luther 1912 mappings", "", "", "", "", "", "", "", ""]
rows << ["# This file extends upstream STEPBible TVTMS with German→KJV", "", "", "", "", "", "", "", ""]
rows << ["# rows for passages where Luther 1912's verse boundaries diverge", "", "", "", "", "", "", "", ""]
rows << ["# from KJV and the upstream German rows do not cover the case.", "", "", "", "", "", "", "", ""]
rows << ["# Generated by script/generate_tvtms_overlay.rb — do not edit by hand.", "", "", "", "", "", "", "", ""]
rows << ["#", "", "", "", "", "", "", "", ""]
rows << ["SourceType", "SourceRef", "StandardRef", "Action", "NoteMarker",
         "Reversification Note", "Versification Note", "Ancient Versions", "Source"]

# --- Psalms ---
luther_psalm_max.keys.sort.each do |ch|
  next if upstream_german_chapters.include?(ch)
  l_max = luther_psalm_max[ch]
  k_max = kjv_psalm_max[ch] || 0
  diff  = l_max - k_max
  next if diff <= 0  # not divergent (or KJV has more — handled elsewhere)

  case diff
  when 1
    # Standard title-as-v1: Luther v1 = title, Luther v2..vN = KJV v1..v(N-1)
    emit(rows, "German", "Psa.#{ch}:1", "Psa.#{ch}:Title", "Renumber title",
         "Luther 1912 numbers the superscription as v1")
    (2..l_max).each do |lv|
      emit(rows, "German", "Psa.#{ch}:#{lv}", "Psa.#{ch}:#{lv - 1}", "Renumber verse")
    end
  when 2
    # Double-line title: Luther v1 + v2 = title (Pss 51, 52, 54*, 60)
    emit(rows, "German", "Psa.#{ch}:1", "Psa.#{ch}:Title", "Renumber title",
         "Luther 1912 numbers the first line of the superscription as v1")
    emit(rows, "German", "Psa.#{ch}:2", "Psa.#{ch}:Title", "Renumber title",
         "Luther 1912 numbers the second line of the superscription as v2")
    (3..l_max).each do |lv|
      emit(rows, "German", "Psa.#{ch}:#{lv}", "Psa.#{ch}:#{lv - 2}", "Renumber verse")
    end
  else
    warn "[overlay] unexpected psalm diff for ch#{ch}: Luther=#{l_max} KJV=#{k_max} (diff=#{diff})"
  end
end

# --- 3 John 1:15 ---
# Luther's v14 = KJV v14 first half, Luther's v15 = KJV v14 second half
emit(rows, "German", "3Jn.1:15", "3Jn.1:14", "MergedPrev verse",
     "Luther 1912 splits KJV 3 John 14 (closing greeting) into v14 + v15")

# --- Revelation 12:18 ---
# Luther's 12:18 = KJV 13:1 first clause ("And I stood upon the sand of the sea")
# Modern critical editions (NA28) agree with Luther.
emit(rows, "German", "Rev.12:18", "Rev.13:1", "Renumber verse",
     "Luther 1912 (and NA28) place 'And I stood upon the sand of the sea' at end of ch12, not start of ch13")

# 5) Write file
FileUtils.mkdir_p(File.dirname(OVERLAY_PATH))
File.open(OVERLAY_PATH, "w") do |f|
  rows.each { |r| f.puts r.join("\t") }
end

n_data = rows.count { |r| !r[0].to_s.start_with?("#") && r[0] != "SourceType" }
puts "wrote #{rows.size} lines (#{n_data} data rows) to #{OVERLAY_PATH}"
